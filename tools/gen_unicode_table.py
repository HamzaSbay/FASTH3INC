"""
Generates src/tokenizer/fh3_tok_unicode.h containing exact Unicode category
intervals for \p{L}, \p{N}, and \s matching Python regex / HuggingFace tokenizers.
"""

import regex
from pathlib import Path

re_l = regex.compile(r"^\p{L}$")
re_n = regex.compile(r"^\p{N}$")
re_s = regex.compile(r"^\s$")

# ASCII flags
ascii_flags = []
for cp in range(128):
    ch = chr(cp)
    f = (1 if re_l.match(ch) else 0) | (2 if re_n.match(ch) else 0) | (4 if re_s.match(ch) else 0)
    ascii_flags.append(f)

# Non-ASCII ranges (128 .. 0x10FFFF)
ranges = []
prev = None
start = 128

for cp in range(128, 0x110000):
    ch = chr(cp)
    f = (1 if re_l.match(ch) else 0) | (2 if re_n.match(ch) else 0) | (4 if re_s.match(ch) else 0)
    if f != prev:
        if prev is not None and prev != 0:
            ranges.append((start, cp - 1, prev))
        start = cp
        prev = f

if prev != 0:
    ranges.append((start, 0x10FFFF, prev))

out_dir = Path("src/tokenizer")
out_dir.mkdir(parents=True, exist_ok=True)
out_file = out_dir / "fh3_tok_unicode.h"

with open(out_file, "w", encoding="utf-8") as f:
    f.write("/* Auto-generated by tools/gen_unicode_table.py - DO NOT EDIT MANUALLY */\n")
    f.write("#ifndef FH3_TOK_UNICODE_H\n")
    f.write("#define FH3_TOK_UNICODE_H\n\n")
    f.write("#include <stdint.h>\n")
    f.write("#include <stddef.h>\n\n")
    f.write("#define FH3_IS_L 0x01\n")
    f.write("#define FH3_IS_N 0x02\n")
    f.write("#define FH3_IS_S 0x04\n\n")

    f.write("typedef struct {\n")
    f.write("    uint32_t start;\n")
    f.write("    uint32_t end;\n")
    f.write("    uint8_t flags;\n")
    f.write("} Fh3UnicodeRange;\n\n")

    f.write("static const uint8_t fh3_ascii_flags[128] = {\n")
    for i in range(0, 128, 16):
        row = ", ".join(f"0x{ascii_flags[i+j]:02x}" for j in range(16))
        f.write(f"    {row},\n")
    f.write("};\n\n")

    f.write(f"static const Fh3UnicodeRange fh3_unicode_ranges[{len(ranges)}] = {{\n")
    for s, e, flg in ranges:
        f.write(f"    {{0x{s:06x}, 0x{e:06x}, 0x{flg:02x}}},\n")
    f.write("};\n\n")

    f.write("static inline uint8_t fh3_unicode_flags(uint32_t cp) {\n")
    f.write("    if (cp < 128) {\n")
    f.write("        return fh3_ascii_flags[cp];\n")
    f.write("    }\n")
    f.write("    int lo = 0;\n")
    f.write(f"    int hi = {len(ranges)} - 1;\n")
    f.write("    while (lo <= hi) {\n")
    f.write("        int mid = lo + (hi - lo) / 2;\n")
    f.write("        if (cp < fh3_unicode_ranges[mid].start) {\n")
    f.write("            hi = mid - 1;\n")
    f.write("        } else if (cp > fh3_unicode_ranges[mid].end) {\n")
    f.write("            lo = mid + 1;\n")
    f.write("        } else {\n")
    f.write("            return fh3_unicode_ranges[mid].flags;\n")
    f.write("        }\n")
    f.write("    }\n")
    f.write("    return 0;\n")
    f.write("}\n\n")

    f.write("#endif /* FH3_TOK_UNICODE_H */\n")

print(f"Generated {out_file} with {len(ranges)} non-ASCII Unicode ranges.")
